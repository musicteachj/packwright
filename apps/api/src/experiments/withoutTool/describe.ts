/**
 * The cases as prompts, written down before any is sent.
 *
 * Shared by both runners — the "without" experiment of 2026-10-09 and the
 * with/without evaluation of stage 19 — so the two cannot describe a case
 * differently. Each passes its own record directory.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { CASES } from './cases'
import { judgeCase, promptFor } from './prompt'
import { promptsInCasesMd, promptsThatChanged } from './records'
import type { LabelSubject } from '@packwright/label-core'

/**
 * Lays out every case and checks the engine still raises its planted defect.
 *
 * Refuses rather than warns: a case whose document lost its defect in the
 * copying would be graded against a finding the label no longer earns.
 */
export function describeCases(
  out: string,
  answeredCaseIds: ReadonlySet<string>,
  /**
   * What `cases.md` says was sent with each prompt. The runner's to state, because
   * the two runners send different things around the same prompts, and this file
   * is the record of what was sent.
   */
  sentWith: string,
  /**
   * Which view `engine.json` records. `drawing` for the records of 2026-10-09 and
   * 2026-10-10, which judged Packwright's own drawing; `described` for the re-check of
   * 2026-10-12, which records what `check_label` answers, declines and the
   * engine's described wording included. The prompts are the same either way: they
   * are read off the drawing.
   */
  subject: LabelSubject = 'drawing',
  /** The command that writes this record, as `cases.md` names it. */
  command = 'run.cli.ts --describe',
  /**
   * A record whose prompts these must be, byte for byte, or nothing is written. Checked
   * before anything is, so a refused re-check does not leave its record holding the
   * prompts it refused. Found by review.
   */
  samePromptsAs?: string,
): Map<string, string> {
  const prompts = new Map<string, string>()
  const engine: unknown[] = []
  const failures: string[] = []
  const markdown: string[] = [
    '# The prompts, exactly as sent',
    '',
    `Generated by \`${command}\` from \`cases.ts\`. ${sentWith}`,
    '',
  ]

  for (const item of CASES) {
    const judged = judgeCase(item, subject)
    const { layout, findings } = judged
    const reported = findings.filter((finding) => finding.severity !== 'pass')
    if (item.expected !== null) {
      const { code, citation } = item.expected
      const hit = reported.some(
        (finding) => finding.code === code && finding.citation.reference === citation,
      )
      if (!hit) failures.push(`${item.id}: the engine no longer raises ${code} citing ${citation}`)
    }
    const prompt = promptFor(item, layout)
    prompts.set(item.id, prompt)
    engine.push({
      caseId: item.id,
      fixtureName: item.fixtureName,
      expected: item.expected,
      findings: reported.map((finding) => ({
        code: finding.code,
        severity: finding.severity,
        citation: finding.citation.reference,
        message: finding.message,
      })),
      ...(subject === 'drawing'
        ? { omissions: layout.omissions.map((omission) => omission.reason) }
        : {
            uncheckable: judged.uncheckable.flatMap((element) =>
              element.reasons.map((reason) => reason.text),
            ),
            declined: judged.declined.map((check) => ({
              ruleId: check.ruleId,
              wants: check.wants,
              ...(check.limit === true ? { limit: true } : {}),
              reason: check.reason,
            })),
          }),
    })
    markdown.push(
      `## ${item.id}`,
      '',
      `From fixture: ${item.fixtureName}. Planted: ${
        item.expected === null
          ? 'nothing (control)'
          : `\`${item.expected.code}\`, ${item.expected.citation}`
      }.`,
      ...(item.note === undefined ? [] : ['', `Note: ${item.note}`]),
      '',
      '```text',
      prompt,
      '```',
      '',
    )
  }

  if (failures.length > 0) {
    console.error(failures.join('\n'))
    process.exit(1)
  }

  if (samePromptsAs !== undefined) {
    const earlier = promptsInCasesMd(readFileSync(join(samePromptsAs, 'cases.md'), 'utf8'))
    const drifted = CASES.map((item) => item.id).filter((id) => earlier.get(id) !== prompts.get(id))
    if (drifted.length > 0) {
      console.error(
        `These prompts differ from ${samePromptsAs}/cases.md, so a re-check would compare ` +
          `different labels: ${drifted.join(', ')}. Nothing was written or sent.`,
      )
      process.exit(1)
    }
  }

  // Before anything is written. `cases.md` is the record of what was sent, so
  // once responses exist it may change only around the prompts — a note, say —
  // and never in them.
  const casesPath = join(out, 'cases.md')
  const enginePath = join(out, 'engine.json')
  const answered = answeredCaseIds
  if (answered.size > 0 && !existsSync(casesPath)) {
    // The records of 2026-10-09 carry no prompt hash; cases.md is the only
    // evidence of what they answered, and a fresh one would be today's prompts.
    console.error(
      'responses.jsonl holds answers but cases.md is missing; restore it from git. Nothing was written.',
    )
    process.exit(1)
  }
  if (answered.size > 0) {
    const changed = promptsThatChanged(
      promptsInCasesMd(readFileSync(casesPath, 'utf8')),
      prompts,
      answered,
    )
    if (changed.length > 0) {
      console.error(
        `responses.jsonl holds answers to the prompts in cases.md, and these would change: ${changed.join(', ')}.` +
          '\nMove responses.jsonl aside to start again; nothing was written.',
      )
      process.exit(1)
    }
  }

  mkdirSync(out, { recursive: true })
  writeFileSync(casesPath, markdown.join('\n'))
  // The engine's findings as the answers were graded against them. Once answers
  // exist the file is kept, and a change in the engine is reported, not written.
  const engineJson = `${JSON.stringify(engine, null, 2)}\n`
  if (answered.size === 0 || !existsSync(enginePath)) writeFileSync(enginePath, engineJson)
  else if (readFileSync(enginePath, 'utf8') !== engineJson)
    console.error(
      'The engine now reports differently on these cases; engine.json is kept as it was graded.',
    )
  return prompts
}
