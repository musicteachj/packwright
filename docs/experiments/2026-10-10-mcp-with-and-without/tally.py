"""Tallies grades/*.json into grading.md. Run from this directory: python3 tally.py

Every figure in grading.md and the README's results comes from here, so a reader can re-derive them from the
per-answer grades rather than take them on trust.
"""
import collections
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MODELS = ['claude-sonnet-5-5', 'claude-haiku-4-5']
ARMS = ['without', 'with']
SHORT = {'claude-sonnet-5-5': 'Sonnet 5.5', 'claude-haiku-4-5': 'Haiku 4.5'}

grades = []
for path in sorted(glob.glob(os.path.join(HERE, 'grades', '*.json'))):
    case = json.load(open(path))
    for answer in case['answers']:
        grades.append({**answer, 'caseId': case['caseId']})


def is_control(case_id):
    return case_id.startswith('C')


def cell(arm, model):
    return [g for g in grades if g['arm'] == arm and g['model'] == model]


def verdict(citation):
    return citation['verdict'].split()[0]


def totals(rows):
    defects = [g for g in rows if not is_control(g['caseId'])]
    cites = [c for g in rows for c in g.get('citations', [])]
    by_verdict = collections.Counter(verdict(c) for c in cites)
    not_real = [o for g in rows for o in g.get('otherClaims', []) if o['grade'] == 'not-real']
    return {
        'answers': len(rows),
        'caught': sum(g['planted'] == 'caught' for g in defects),
        'partly': sum(g['planted'] == 'partly' for g in defects),
        'missed': sum(g['planted'] == 'missed' for g in defects),
        'defects': len(defects),
        'falseClearances': sum(bool(g.get('falseClearance')) for g in rows),
        'withMorF': sum(any(verdict(c) in ('M', 'F') for c in g.get('citations', [])) for g in rows),
        'withF': sum(any(verdict(c) == 'F' for c in g.get('citations', [])) for g in rows),
        'V': by_verdict['V'], 'M': by_verdict['M'], 'F': by_verdict['F'], 'U': by_verdict['U'],
        'notReal': len(not_real),
        'notRealOnControls': sum(
            1 for g in rows if is_control(g['caseId']) for o in g.get('otherClaims', []) if o['grade'] == 'not-real'
        ),
    }


ROWS = [
    ('Planted defect caught', lambda t: f"{t['caught']} of {t['defects']}"),
    ('Partly', lambda t: t['partly']),
    ('Missed', lambda t: t['missed']),
    ('False clearances', lambda t: t['falseClearances']),
    ('Answers with an M or F citation', lambda t: f"{t['withMorF']} of {t['answers']}"),
    ('Answers with an F citation', lambda t: f"{t['withF']} of {t['answers']}"),
    ('Citations V · M · F · U', lambda t: f"{t['V']} · {t['M']} · {t['F']} · {t['U']}"),
    ('Claims of a requirement that does not exist', lambda t: t['notReal']),
    ('…of them on the two controls', lambda t: t['notRealOnControls']),
]

out = ['# Grading', '', 'Generated by `tally.py` from `grades/`. Rubric: `README.md` § Rubric. V verified · M misattributed '
       '(exists, does not say that) · F does not exist · U not verifiable in-session.', '', '## Totals', '']
cols = [(arm, model) for arm in ARMS for model in MODELS]
out.append('| | ' + ' | '.join(f'{SHORT[m]}, {a}' for a, m in cols) + ' |')
out.append('|---|' + '---|' * len(cols))
table = {key: totals(cell(*key)) for key in cols}
for label, fn in ROWS:
    out.append(f'| {label} | ' + ' | '.join(str(fn(table[key])) for key in cols) + ' |')

# The "with" half's own measures.
out += ['', '## How the tools were used (the "with" half)', '']
out.append('| | ' + ' | '.join(SHORT[m] for m in MODELS) + ' |')
out.append('|---|' + '---|' * len(MODELS))
tool_rows = []
for model in MODELS:
    rows = [g for g in cell('with', model) if g.get('tool')]
    tools = [g['tool'] for g in rows]
    # One grader listed declined checks among the findings relayed, as "declined: <rule>". The rubric's
    # relay is of findings, so those are counted on their own rather than mixed in.
    relays = [f for t in tools for f in t.get('relay', {}).get('findings', [])
              if not str(f.get('code', '')).lower().startswith('declined')]
    sources = collections.Counter(e['source'] for t in tools for e in t.get('errorSources', []))
    tool_rows.append({
        'calls': sum(t.get('checkLabelCalls', 0) for t in tools),
        'refusals': sum(t.get('schemaRefusals', 0) for t in tools),
        'withTranscriptionError': sum(bool(t.get('transcriptionErrors')) for t in tools),
        'transcriptionErrors': sum(len(t.get('transcriptionErrors', [])) for t in tools),
        'changedPlanted': sum(
            any(e.get('changedPlantedVerdict') for e in t.get('transcriptionErrors', [])) for t in tools
        ),
        'relayed': collections.Counter(f['relayed'] for f in relays),
        'notice': sum(bool(t.get('relay', {}).get('notice')) for t in tools),
        'answers': len(tools),
        'sources': sources,
    })
for label, fn in [
    ('check_label calls', lambda r: r['calls']),
    ('…refused by the input schema', lambda r: r['refusals']),
    ('Answers with a transcription error', lambda r: f"{r['withTranscriptionError']} of {r['answers']}"),
    ('Transcription errors', lambda r: r['transcriptionErrors']),
    ('…answers where one changed the tool\'s verdict on the planted defect, in some call', lambda r: r['changedPlanted']),
    ('Tool findings relayed faithfully · wrongly · dropped',
     lambda r: f"{r['relayed']['faithful']} · {r['relayed']['wrong']} · {r['relayed']['dropped']}"),
    ('Answers saying a clean result is not compliance', lambda r: f"{r['notice']} of {r['answers']}"),
    ('Errors from the engine · the transcription · the model',
     lambda r: f"{r['sources']['engine']} · {r['sources']['transcription']} · {r['sources']['model']}"),
]:
    out.append(f'| {label} | ' + ' | '.join(str(fn(r)) for r in tool_rows) + ' |')

out += ['', '## Per case', '', '| Case | Model | Half | Runs: planted | False clearances | V/M/F/U |', '|---|---|---|---|---|---|']
for case in sorted({g['caseId'] for g in grades}):
    for model in MODELS:
        for arm in ARMS:
            rows = sorted((g for g in grades if g['caseId'] == case and g['model'] == model and g['arm'] == arm),
                          key=lambda g: g['run'])
            if not rows:
                continue
            c = collections.Counter(verdict(x) for g in rows for x in g.get('citations', []))
            planted = ' · '.join('—' if g['planted'] is None else g['planted'] for g in rows)
            out.append(f"| {case} | {model} | {arm} | {planted} | {sum(bool(g.get('falseClearance')) for g in rows)} | "
                       f"{c['V']}/{c['M']}/{c['F']}/{c['U']} |")

out += ['', '## Engine errors the graders attributed', '']
engine = [(g, e) for g in grades if g.get('tool') for e in g['tool'].get('errorSources', []) if e['source'] == 'engine']
if not engine:
    out.append('None.')
for g, e in engine:
    out.append(f"- {g['caseId']} {g['model']} run {g['run']}: {e['conclusion']} — {e['why']}")

out += ['', '## Every transcription error', '', '| Case | Model | Run | Field | Label says | Sent | Changed planted |',
        '|---|---|---|---|---|---|---|']
for g in grades:
    for e in (g.get('tool') or {}).get('transcriptionErrors', []):
        out.append(f"| {g['caseId']} | {g['model']} | {g['run']} | {e['field']} | {e['labelSays']} | {e['sent']} | "
                   f"{'yes' if e.get('changedPlantedVerdict') else 'no'} |")

out += ['', '## Every M and F citation', '', '| Case | Model | Half | Run | Verdict | Cited | Claimed | Source says |',
        '|---|---|---|---|---|---|---|---|']
for g in grades:
    for c in g.get('citations', []):
        if verdict(c) in ('M', 'F'):
            cells = [g['caseId'], g['model'], g['arm'], str(g['run']), c['verdict'], c['ref'], c['claim'], c.get('evidence', '')]
            out.append('| ' + ' | '.join(x.replace('|', '\\|').replace('\n', ' ') for x in cells) + ' |')

open(os.path.join(HERE, 'grading.md'), 'w').write('\n'.join(out) + '\n')
print(f'{len(grades)} answers tallied into grading.md')
